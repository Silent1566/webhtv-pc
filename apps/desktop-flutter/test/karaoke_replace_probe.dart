import 'dart:convert';
import 'dart:io';

import 'package:webhtv_pc/core/karaoke/karaoke.dart';
import 'package:webhtv_pc/services/karaoke/track_repository.dart';

import 'karaoke_repository_fixture.dart' show fixture;

void check(bool condition, String name) {
  if (!condition) throw StateError(name);
  stdout.writeln('PASS: $name');
}

Future<void> main() async {
  final root = await Directory.systemTemp.createTemp('karaoke_replace');
  final repository = KaraokeTrackRepository(root);
  const a = KaraokeMedia(
    key: 'a',
    url: 'a',
    title: 'A',
    artist: 'A',
    durationMs: 1,
  );
  const b = KaraokeMedia(
    key: 'b',
    url: 'b',
    title: 'B',
    artist: 'B',
    durationMs: 1,
  );
  const c = KaraokeMedia(
    key: 'c',
    url: 'c',
    title: 'C',
    artist: 'C',
    durationMs: 1,
  );
  try {
    await repository.importText(a, 'a', fixture);
    await repository.importText(b, 'b', fixture);
    await repository.importGenerated(
      c,
      const KaraokePitchTrack(
        text: fixture,
        noteCount: 3,
        observed: 3,
        pitched: 3,
      ),
    );
    final old = await repository.exportUserData();
    final cache = File(
      '${repository.cacheTrackDirectory.path}/${repository.signatureOf(c)}.generated-pitch.txt',
    );
    final cacheBytes = await cache.readAsBytes();
    check(
      old.length == 2 && (await repository.listUserData()).length == 2,
      'export/list exclude generated cache',
    );
    final name = '${repository.signatureOf(c)}.txt';
    final replaced = await repository.importUserData({
      name: utf8.encode(fixture),
    }, replace: true);
    check(
      replaced.restored == 1 &&
          replaced.skipped == 0 &&
          (await repository.exportUserData()).length == 1,
      'replace removes extra user tracks',
    );
    check(
      await repository.load(a) == null &&
          await repository.load(b) == null &&
          await repository.load(c) != null,
      'replacement binds only requested media',
    );
    check(
      base64.encode(await cache.readAsBytes()) == base64.encode(cacheBytes),
      'replace preserves generated bytes',
    );
    await repository.importUserData(old, replace: true);
    check(
      (await repository.exportUserData()).keys.join(',') != name &&
          await repository.load(a) != null &&
          await repository.load(b) != null,
      'old export exact rollback removes new track',
    );
    final oldDigest = jsonEncode(
      (await repository.exportUserData()).map(
        (k, v) => MapEntry(k, base64.encode(v)),
      ),
    );
    for (final invalid in [
      {'../$name': utf8.encode(fixture)},
      {'$name/': utf8.encode(fixture)},
      {name.toUpperCase(): utf8.encode(fixture), name: utf8.encode(fixture)},
      {'${repository.signatureOf(c)}.generated.txt': utf8.encode(fixture)},
      {
        name: [0xff],
      },
      {name: utf8.encode('not ultrastar')},
      {name: utf8.encode('#BPM:NaN\n#GAP:0\n: 0 1 69 la\nE')},
      {name: utf8.encode('#BPM:60\n#GAP:0\nF 0 1 69 la\nE')},
      {name: List.filled(512 * 1024 + 1, 65)},
    ]) {
      var rejected = false;
      try {
        await repository.importUserData(invalid, replace: true);
      } on KaraokeUserDataException catch (error) {
        rejected = error.originalDataRestored;
      }
      check(rejected, 'strict full validation rejects ${invalid.keys.first}');
      final after = jsonEncode(
        (await repository.exportUserData()).map(
          (k, v) => MapEntry(k, base64.encode(v)),
        ),
      );
      check(
        after == oldDigest,
        'failed replacement leaves old bytes unchanged',
      );
    }
    final merge = await repository.importUserData({name: utf8.encode(fixture)});
    check(
      merge.restored == 1 && (await repository.exportUserData()).length == 3,
      'default merge retained',
    );
    await repository.importUserData({}, replace: true);
    check(
      (await repository.exportUserData()).isEmpty &&
          (await repository.listUserData()).isEmpty,
      'empty map precisely clears user set',
    );
    check(
      await cache.exists() &&
          base64.encode(await cache.readAsBytes()) == base64.encode(cacheBytes),
      'empty replace keeps generated cache',
    );
    final blocker = File('${root.path}/blocked');
    await blocker.writeAsString('block directory creation');
    final blocked = KaraokeTrackRepository(Directory('${blocker.path}/child'));
    var ioRejected = false;
    try {
      await blocked.importUserData({name: utf8.encode(fixture)}, replace: true);
    } on KaraokeUserDataException catch (error) {
      ioRejected = error.originalDataRestored;
    }
    check(
      ioRejected && await blocker.readAsString() == 'block directory creation',
      'staging IO failure has rollback-safe error',
    );
    await repository.importUserData(old, replace: true);
    check(
      (await repository.exportUserData()).length == 2,
      'rollback from empty restores exact old set',
    );
  } finally {
    await root.delete(recursive: true);
  }
  stdout.writeln('ALL REPLACEMENT PROBES PASSED');
}
